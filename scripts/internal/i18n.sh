# Protect against double-sourcing
if [ -n "${_ORACLE_I18N_SH_LOADED:-}" ]; then
  return 0 2>/dev/null || exit 0
fi
_ORACLE_I18N_SH_LOADED=true

# ------------------------------------------------------------------------------
# 1. Language Resolution
# Priority: CLI argument ($CLI_LANG) > .env ($CLI_LANG) > System ($LANG) > Default "en"
# ------------------------------------------------------------------------------
resolve_cli_lang() {
  local l="${CLI_LANG:-${LANGUAGE:-${LANG:-en}}}"
  l=$(echo "$l" | tr '[:upper:]' '[:lower:]' | cut -d'_' -f1 | cut -d'.' -f1)
  case "$l" in
    et|est|ee) echo "et" ;;
    fi|fin|suomi) echo "fi" ;;
    sv|swe|se) echo "sv" ;;
    lv|lav)    echo "lv" ;;
    lt|lit)    echo "lt" ;;
    *)         echo "en" ;;
  esac
}

export ACTIVE_CLI_LANG="$(resolve_cli_lang)"

# ------------------------------------------------------------------------------
# 2. String Catalog Storage (POSIX & Bash 3.2+ Compatible)
# ------------------------------------------------------------------------------
_reg_msg() {
  local lang="$1"
  local key="$2"
  local val="$3"
  printf -v "_I18N_${lang}_${key}" "%s" "$val" 2>/dev/null || eval "_I18N_${lang}_${key}=\"\$val\""
}

_get_msg_fmt() {
  local key="$1"
  local lang="${CLI_LANG:-${ACTIVE_CLI_LANG:-en}}"
  case "$lang" in
    et*|est*)   lang="et" ;;
    fi*|fin*)   lang="fi" ;;
    sv*|swe*)   lang="sv" ;;
    lv*|lav*)   lang="lv" ;;
    lt*|lit*)   lang="lt" ;;
    *)          lang="en" ;;
  esac
  local var_lang="_I18N_${lang}_${key}"
  local var_en="_I18N_en_${key}"
  local fmt=""
  if [ -n "${ZSH_VERSION:-}" ]; then
    fmt="${(P)var_lang}"
    [ -z "$fmt" ] && fmt="${(P)var_en}"
  else
    eval "fmt=\"\${${var_lang}:-}\""
    [ -z "$fmt" ] && eval "fmt=\"\${${var_en}:-}\""
  fi
  [ -z "$fmt" ] && fmt="$key"
  printf "%s" "$fmt"
}

# ------------------------------------------------------------------------------
# 3. Output Functions (Zero-Fork)
# ------------------------------------------------------------------------------

# Directly print formatted message with trailing newline
msg_print() {
  local key="$1"; shift
  local fmt
  fmt="$(_get_msg_fmt "$key")"
  # shellcheck disable=SC2059
  printf "${fmt}\n" "$@"
}

# Directly print error message with trailing newline to stderr
msg_err() {
  local key="$1"; shift
  local fmt
  fmt="$(_get_msg_fmt "$key")"
  # shellcheck disable=SC2059
  printf "${fmt}\n" "$@" >&2
}

# Format string without newline (for inline capture)
msg_str() {
  local key="$1"; shift
  local fmt
  fmt="$(_get_msg_fmt "$key")"
  # shellcheck disable=SC2059
  printf "${fmt}" "$@"
}

